#!/usr/bin/env python3
"""Plot size metrics: number of Gaussians and bit budget utilization."""
from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def _read_summary_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Plot size metrics (Gaussians count, bit budget utilization)"
    )
    parser.add_argument("--summary-csv", required=True, type=str,
                        help="CSV generated by aggregate_selection_sweep_0507.py")
    parser.add_argument("--out-dir", required=True, type=str,
                        help="Directory for output PNG plots")
    args = parser.parse_args()

    summary_csv = Path(args.summary_csv)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = _read_summary_csv(summary_csv)
    if not rows:
        raise ValueError(f"No rows found in summary CSV: {summary_csv}")

    grouped: dict[str, list[dict[str, float]]] = defaultdict(list)
    for r in rows:
        grouped[r["scheme"]].append({
            "budget_mb": float(r["budget_mb"]),
            "selected_gaussians_mean": float(r["selected_gaussians_mean"]),
            "selected_gaussians_std": float(r["selected_gaussians_std"]),
            "used_ratio_mean": float(r["used_ratio_mean"]),
            "used_ratio_std": float(r["used_ratio_std"]),
        })

    for scheme in grouped:
        grouped[scheme].sort(key=lambda x: x["budget_mb"])

    # Plot 1: number of Gaussians vs bit budget
    plt.figure(figsize=(8.5, 5.2))
    for scheme, vals in sorted(grouped.items()):
        x = [v["budget_mb"] for v in vals]
        y = [v["selected_gaussians_mean"] for v in vals]
        yerr = [v["selected_gaussians_std"] for v in vals]
        plt.errorbar(x, y, yerr=yerr, marker="o", linewidth=1.8, capsize=3, label=scheme)
    plt.xlabel("Bit Budget (MB)")
    plt.ylabel("Number of Gaussians (mean across views)")
    plt.title("Number of Gaussians vs Bit Budget")
    plt.grid(alpha=0.25)
    plt.legend()
    plt.tight_layout()
    gauss_plot = out_dir / "selected_gaussians_vs_budget.png"
    plt.savefig(gauss_plot, dpi=220)

    # Plot 2: bit budget utilization vs bit budget
    plt.figure(figsize=(8.5, 5.2))
    for scheme, vals in sorted(grouped.items()):
        x = [v["budget_mb"] for v in vals]
        y = [v["used_ratio_mean"] * 100.0 for v in vals]
        yerr = [v["used_ratio_std"] * 100.0 for v in vals]
        plt.errorbar(x, y, yerr=yerr, marker="o", linewidth=1.8, capsize=3, label=scheme)
    plt.xlabel("Bit Budget (MB)")
    plt.ylabel("Bit Budget Utilization (%)")
    plt.title("Bit Budget Utilization vs Bit Budget")
    plt.ylim(0.0, 105.0)
    plt.grid(alpha=0.25)
    plt.legend()
    plt.tight_layout()
    util_plot = out_dir / "budget_utilization_vs_budget.png"
    plt.savefig(util_plot, dpi=220)

    print(f"Wrote plot: {gauss_plot}")
    print(f"Wrote plot: {util_plot}")


if __name__ == "__main__":
    main()
